// New listing wizard: lookup prefill, 10% rule, create on-market listing, authority on Today, edit via simple editor.
const puppeteer = require('puppeteer-core');
const path = require('path');
const [file, dir] = process.argv.slice(2);
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new' });
  const page = await browser.newPage(); await page.setViewport({ width: 1500, height: 1000 });
  const errs = []; page.on('console', m => { if (m.type() === 'error' && !/favicon/.test(m.text())) errs.push(m.text()); }); page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await page.goto('file:///' + path.resolve(file).replace(/\\/g, '/'), { waitUntil: 'load', timeout: 120000 }); await wait(1200);
  await page.evaluate(() => localStorage.clear()); await page.reload({ waitUntil: 'load' }); await wait(1200);
  const out = {};
  const click = async s => { const ok = await page.evaluate(s => { const b = document.querySelector(s); if (b) { b.click(); return true; } return false; }, s); await wait(200); return ok; };
  const type = async (sel, val) => { await page.evaluate(s => { const el = document.querySelector(s); if (el) el.value = ''; }, sel); await page.type(sel, val); };
  await page.evaluate(() => { location.hash = '/properties/add-property'; }); await wait(300);
  out.step1 = await page.evaluate(() => document.querySelector('.cw-main h2')?.innerText);
  await type('#nl1-address', '14 Grant Street, Preston'); await wait(300);
  out.lookup = await page.evaluate(() => document.querySelector('.cw-main .alert.info')?.innerText.slice(0, 120));
  await click('[data-action="cwNlUseLookup"]');
  out.prefilled = await page.evaluate(() => ({ beds: document.querySelector('#nl1-beds')?.value, cls: document.querySelector('#nl1-cls')?.value, land: document.querySelector('#nl1-land')?.value }));
  await page.screenshot({ path: dir + '/l1.png' });
  await click('[data-action="cwNlNext"]');
  out.step2 = await page.evaluate(() => document.querySelector('.cw-main h2')?.innerText);
  await page.evaluate(() => { document.querySelector('input[name="ltype"][value="On market listing"]').click(); });
  await type('#nl2-low', '1000000'); await type('#nl2-high', '1200000'); await wait(200);
  out.priceNoteWide = await page.evaluate(() => document.querySelector('.cw-main .alert.warn')?.innerText.slice(0, 80));
  await click('[data-action="cwNlNext"]');
  out.blocked = await page.evaluate(() => document.querySelector('.cw-err')?.innerText);
  await type('#nl2-high', '1100000'); await wait(200);
  await click('[data-action="cwNlNext"]');
  out.step3 = await page.evaluate(() => document.querySelector('.cw-main h2')?.innerText);
  out.vendorPrefill = await page.evaluate(() => ({ name: document.querySelector('#nl3-vname')?.value, mobile: document.querySelector('#nl3-vmobile')?.value }));
  await page.screenshot({ path: dir + '/l3.png' });
  await click('[data-action="cwNlCreate"]'); await wait(300);
  out.card = await page.evaluate(() => ({ title: document.querySelector('#overlay h2')?.innerText, items: [...document.querySelectorAll('.cw-jn-done strong')].map(x => x.innerText) }));
  await page.screenshot({ path: dir + '/l4.png' });
  const dealId = await page.evaluate(() => [...document.querySelectorAll('[data-action="cwJnOpen"]')].map(b => b.dataset.id).find(r => /^\/properties\/D-/.test(r))?.split('/')[2]);
  await click('[data-action="close"]');
  await page.evaluate(id => { location.hash = '/properties/' + id; }, dealId); await wait(300);
  out.property = await page.evaluate(() => ({ h1: document.querySelector('.cw-main h1')?.innerText, price: document.querySelector('.cw-main h1')?.nextElementSibling?.innerText, done: [...document.querySelectorAll('.cw-jn-step.done')].map(x => x.innerText.trim()), next: document.querySelector('.cw-jn-strip b')?.innerText }));
  await page.evaluate(() => document.querySelector('[data-action="route"][data-id="today"]').click()); await wait(300);
  out.todayHas = await page.evaluate(() => { const t = document.querySelector('#geevee-worklist')?.innerText || ''; return { authority: /Authority · Marion/i.test(t), invite: /claim 14 Grant|Marion Doyle/i.test(t) }; });
  // simple editor
  await page.evaluate(id => { location.hash = '/properties/edit/' + id; }, dealId); await wait(300);
  out.editBanner = await page.evaluate(() => !!document.querySelector('[data-action="cwGo"][data-id^="/properties/add-property?edit="]'));
  await click('[data-action="cwGo"][data-id^="/properties/add-property?edit="]'); await wait(300);
  out.editLoaded = await page.evaluate(() => ({ h1: document.querySelector('.cw-main h1')?.innerText, addr: document.querySelector('#nl1-address')?.value, beds: document.querySelector('#nl1-beds')?.value }));
  await type('#nl1-beds', '4'); await click('[data-action="cwNlNext"]'); await click('[data-action="cwNlNext"]'); await click('[data-action="cwNlCreate"]'); await wait(300);
  out.editCard = await page.evaluate(() => document.querySelector('#overlay h2')?.innerText);
  await click('[data-action="close"]');
  out.bedsAfter = await page.evaluate(id => { location.hash = '/properties/' + id; return null; }, dealId); await wait(300);
  out.bedsAfter = await page.evaluate(() => document.querySelector('.cw-main .cw-feature, .cw-main h1 + div')?.innerText);
  // full form still reachable
  await page.evaluate(() => { location.hash = '/properties/add-property?full=1'; }); await wait(300);
  out.fullForm = await page.evaluate(() => /Choose Listing Type|Property Information/i.test(document.querySelector('.cw-main')?.innerText || ''));
  out.errs = errs;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
